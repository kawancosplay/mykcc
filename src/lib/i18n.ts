export function getFormTranslation(lang: LanguageCode): FormSpecificTranslations {
  const current = FORM_TRANSLATIONS_DATA[lang];
  const en = FORM_TRANSLATIONS_DATA.en!;
  const id = FORM_TRANSLATIONS_DATA.id!;
  
  if (current) {
    return { ...en, ...current };
  }
  
  // For other languages, generate smart fallback based on base translation
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return {
    ...en,
    nameLabel: dict.cosplayName || en.nameLabel,
    namePrivacyNotice: dict.namePrivacyNotice || en.namePrivacyNotice,
    whatsappLabel: dict.phone ? `${dict.phone} (WhatsApp)` : en.whatsappLabel,
    whatsappNotice: en.whatsappNotice,
    emailLabel: dict.email || en.emailLabel,
    ageDesc: dict.exactAgeOptional || en.ageDesc,
    locationTitle: `${dict.country} & ${dict.city}`,
    roleTitle: dict.role || en.roleTitle,
    fandomTitle: dict.fandom || en.fandomTitle,
    experienceTitle: dict.experience || en.experienceTitle,
    socialMediaTitle: dict.socialMedia || en.socialMediaTitle,
    portfolioTitle: dict.portfolio || en.portfolioTitle,
    avatarTitle: dict.avatar || en.avatarTitle,
    reasonTitle: dict.reason || en.reasonTitle,
    codeOfConductTitle: dict.codeOfConduct || en.codeOfConductTitle,
    submittingText: dict.submitButton ? '...' : en.submittingText,
    roleOthers: lang === 'id' ? id.roleOthers : en.roleOthers,
    roleOthersPlaceholder: lang === 'id' ? id.roleOthersPlaceholder : en.roleOthersPlaceholder,
  };
}
